let actual = "en";
export const idioma = () => actual;
export function ponerIdioma(l) { actual = D[l] ? l : "en"; document.documentElement.lang = actual; }

export function t(clave, v = {}) {
  const s = D[actual][clave] ?? D.en[clave] ?? clave;
  return s.replace(/\{(\w+)\}/g, (_, k) => (v[k] ?? ""));
}
// un texto que viaja por la red puede ser [clave, valores] o un texto ya hecho
export const tr = x => (Array.isArray(x) ? t(x[0], x[1]) : x ?? "");

export function traducirPagina() {
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-ph]")) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
}
